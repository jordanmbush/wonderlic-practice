#!/usr/bin/env bash
# Post-deploy smoke checks against the live origin.
#
# Deliberately narrow: this asks "did a working site actually land at this
# URL", not "does the app work". What can only break HERE is the delivery —
# DNS, the certificate, cache headers, the error document, and whether every
# page the build produced actually got uploaded. A deploy can succeed, report
# green, and leave half the site missing; that is the failure this exists for.
#
# Three traps are designed around below, all of them learned on the sibling
# repo this script is modelled on. Two of them reported a failing deploy that
# was in fact fine, which is the more expensive kind of wrong: a smoke check
# nobody believes is a smoke check nobody reads.
#
# **A hand-maintained page list only knows about the pages it was written
# with.** A release that adds a page passes a stale list while the new page
# 404s. So the list comes from the DEPLOYED sitemap instead: the sitemap is
# generated by the build, which makes it that build's own statement of what
# should exist, and the one list that cannot drift. A page that silently
# failed to upload now fails here, including a page nobody thought to add to
# this file.
#
# ⚠️ That makes the sitemap load-bearing. The site needs a sitemap for search
# anyway — it is the entire traffic plan — but if `@astrojs/sitemap` is ever
# dropped from astro.config.mjs, this script goes red and it is this comment,
# not a bug, that explains why.
#
# **It ran inside the invalidation window.** CloudFront keeps serving a cached
# negative answer for a few seconds after an invalidation is issued, so the
# first request for a page added in this very release can 404 while the deploy
# is perfectly healthy. Every check therefore retries, with a doubling gap.
#
# **It lost a race with itself.** `curl | grep -q` under `pipefail` reports
# failure when grep matches EARLY, because grep's exit closes the pipe and curl
# dies of SIGPIPE. The probes below never pipe curl into grep; see the note
# above them.
#
# Usage: bash scripts/post-deploy-smoke.sh <base-url>
#   e.g. bash scripts/post-deploy-smoke.sh https://freewonderlicpractice.com
#        bash scripts/post-deploy-smoke.sh https://d111111abcdef8.cloudfront.net
set -euo pipefail

BASE="${1:?usage: post-deploy-smoke.sh <base-url>}"
# A trailing slash would turn every "${BASE}${path}" into a double slash, which
# S3 treats as a different (missing) key.
BASE="${BASE%/}"

# Retries back off: the gap doubles each time, so the waits are 3, 6, 12, 24
# and 48 seconds — about a minute and a half of patience across six attempts,
# and none of it spent when the site is healthy.
#
# A FIXED gap has to choose between being quick to report a real outage and
# being patient with a page added in this release; doubling does not, because
# the early attempts stay cheap. A flat 16 seconds total was measured as too
# short against CloudFront's propagation window, and filed a "deploy failed"
# issue for a deploy that was fine.
ATTEMPTS="${SMOKE_ATTEMPTS:-6}"
DELAY="${SMOKE_DELAY:-3}"

# A floor, not an inventory. Its only job is to catch a sitemap that parsed to
# nothing — which would otherwise leave the page loop with no work to do and
# report a clean run, the precise failure that section exists to catch.
#
# Four is deliberately below the real count (the home page, /privacy, /terms,
# /what-is-the-wonderlic and the guides are all in the sitemap) so that adding
# or retiring one guide never fails a healthy deploy. Raise it if you ever want
# this to mean "the sitemap still lists what it used to" rather than "the
# sitemap was readable".
MIN_PAGES="${SMOKE_MIN_PAGES:-4}"

fails=0

# --- probes: each echoes one word, so a check is a string comparison ---------
#
# None of these pipe curl into `grep -q`, and that is not a style preference.
# `grep -q` exits the instant it matches, which closes the pipe while curl is
# still writing; curl dies of SIGPIPE and exits 141, `pipefail` promotes that
# to the pipeline's status, and the `if` takes the else branch — reporting "no"
# BECAUSE the string was found early enough. It is intermittent, it looks like
# a flaky site, and it is not.
#
# So each probe fetches into a variable first and matches against that. No
# pipeline, nothing to receive a SIGPIPE, and the result depends on the
# response rather than on who won a race.

status() { curl -sS -o /dev/null -w "%{http_code}" --max-time 15 "$1"; }

body_contains() {
  local body
  body="$(curl -sS --max-time 15 "$1" || true)"
  if grep -qF -- "$2" <<<"$body"; then echo "yes"; else echo "no"; fi
}

header_matches() {
  local headers line
  headers="$(curl -sSI --max-time 15 "$1" | tr -d '\r' || true)"
  # Two greps, but never piped into each other, for the reason above.
  line="$(grep -i -- "^$2:" <<<"$headers" || true)"
  if grep -qi -- "$3" <<<"$line"; then echo "yes"; else echo "no"; fi
}

# The certificate, checked as a certificate rather than inferred from a 200.
#
# `-k` is never passed anywhere in this file, so curl verifies the chain by
# default and a 200 does already imply a usable cert. This asks the question
# directly anyway: `%{ssl_verify_result}` is 0 only when the chain validated,
# and `--proto '=https'` refuses to quietly follow the request to plain HTTP.
# The first production deploy blocks on ACM's DNS validation, and a certificate
# that is issued but not yet attached to the distribution is a real state the
# deploy can end in.
#
# Note: on a curl built against Secure Transport (some macOS builds) this
# field can read 0 regardless, so treat a local pass as weaker evidence than
# the CI one. The GitHub runner's curl is OpenSSL-backed and reports honestly.
tls_verified() {
  local result
  result="$(curl -sS -o /dev/null --max-time 15 --proto '=https' \
    -w '%{ssl_verify_result}' "$1" 2>/dev/null || echo "unreachable")"
  if [ "$result" = "0" ]; then echo "yes"; else echo "no"; fi
}

# --- the retry harness -------------------------------------------------------

# try <label> <expected> <probe> [args...]
#
# The probe is passed unevaluated so it can be run again. Anything it writes to
# stderr is dropped and a non-zero exit is swallowed — a probe that fails to run
# is simply a probe that did not return what we wanted, and gets another go.
try() {
  local label="$1" expected="$2"
  shift 2
  local actual="" attempt=1 wait="$DELAY"
  while [ "$attempt" -le "$ATTEMPTS" ]; do
    actual="$("$@" 2>/dev/null || true)"
    if [ "$actual" = "$expected" ]; then
      if [ "$attempt" -eq 1 ]; then
        echo "  ✓ ${label}"
      else
        # Worth saying out loud. A check that needs three goes today is a check
        # that needs six after the next thing slows down.
        echo "  ✓ ${label} — after ${attempt} attempts"
      fi
      return 0
    fi
    if [ "$attempt" -lt "$ATTEMPTS" ]; then
      sleep "$wait"
      wait=$((wait * 2))
    fi
    attempt=$((attempt + 1))
  done
  echo "  ✗ ${label} — got '${actual}', want '${expected}'"
  fails=$((fails + 1))
  return 0
}

echo "Smoke-testing ${BASE}"

# --- is anything there at all? -----------------------------------------------

# Before anything else, because every check below retries: against a dead host
# each one would burn its full budget on connection timeouts and the job would
# hit its own timeout long before it finished reporting. One clear failure now
# beats thirty slow ones.
try "landing page serves" "200" status "${BASE}/"
if [ "$fails" -gt 0 ]; then
  echo "✗ the origin is not serving — stopping here rather than timing out"
  exit 1
fi

# --- the certificate ---------------------------------------------------------

# Skipped for a plain-HTTP base URL, which only happens when someone points
# this at a local preview. Every real origin here is https.
case "$BASE" in
  https://*)
    try "TLS certificate validates" "yes" tls_verified "${BASE}/"
    ;;
  *)
    echo "  – TLS check skipped (base URL is not https)"
    ;;
esac

# --- every page the deployed build claims to have ----------------------------

echo "Pages, from the deployed sitemap:"

# Sitemap entries are absolute and always carry the *canonical* host, because
# that is what a sitemap is for. Only the path is used here, and it is probed
# against the base we were asked to test — otherwise pointing this script at a
# dev origin would quietly check production and pass.
locs() {
  curl -sS --max-time 15 "$1" | grep -o "<loc>[^<]*</loc>" |
    sed -e "s|<[^>]*>||g" -e "s|^https\{0,1\}://[^/]*||"
}

# The `|| true` is load-bearing under `set -e`: `grep -o` exits non-zero when a
# sitemap contains no entries, and an assignment whose command substitution
# fails aborts the script — which is how an empty sitemap can make this exit
# silently instead of reporting the empty sitemap. Let it produce nothing and
# let the count guard below say so.
pages=""
for map in $(locs "${BASE}/sitemap-index.xml" || true); do
  pages="${pages}$(locs "${BASE}${map}" || true)
"
done

pagecount=0
while IFS= read -r path; do
  if [ -n "$path" ]; then
    try "${path}" "200" status "${BASE}${path}"
    pagecount=$((pagecount + 1))
  fi
done <<<"$pages"

if [ "$pagecount" -lt "$MIN_PAGES" ]; then
  echo "  ✗ the sitemap yielded only ${pagecount} page(s), so nothing was really checked"
  fails=$((fails + 1))
else
  # Only that the list was worth walking. Whether each page served is the
  # per-page result above, which is where a failure gets reported.
  echo "  ✓ ${pagecount} pages listed in the sitemap"
fi

# --- the practice app --------------------------------------------------------
#
# Deliberately NOT in the sitemap: /practice/ paints itself with JavaScript, so
# its prerendered body is an empty <main>. It carries `noindex` and is filtered
# out in astro.config.mjs, and robots.txt asks crawlers not to bother with it.
#
# All of that is correct for search, and all of it quietly removed the one page
# people actually use from the loop above, which discovers pages FROM the
# sitemap. So it is named here by hand. There is no way to derive it from the
# sitemap — being absent from the sitemap is the whole point of it.
echo "Practice app (noindex, so not in the sitemap):"
try "/practice/" "200" status "${BASE}/practice/"
# The noindex is the reason it is excluded, so it is worth asserting: if the
# practice page lost its robots tag it would start competing in search with the
# guides written to rank, using a page that renders as two words to a crawler.
try "/practice/ is noindex" "yes" \
  body_contains "${BASE}/practice/" 'name="robots" content="noindex'

# --- everything that isn't a page --------------------------------------------

echo "Delivery:"

# Both of these are how Google finds and crawls the site, which for a site with
# no ad budget is the only way anyone finds it. A missing robots.txt is not a
# small cosmetic gap here.
try "sitemap serves" "200" status "${BASE}/sitemap-index.xml"
try "robots serves" "200" status "${BASE}/robots.txt"

# A wrong URL must answer 404. Two separate things make that work — the
# distribution's custom error responses being emptied, and the CloudFront
# service principal holding `s3:ListBucket` — and sst.config.ts explains both.
# Break either and a typo'd URL answers `502 Error from cloudfront`, which
# reads as a broken site to a person and as a server fault to a crawler.
try "unknown path 404s (not 502)" "404" status "${BASE}/definitely-not-a-page"

# The cheapest possible proof we are serving OUR site and not a parked domain,
# a Cloudflare error page or somebody else's stale distribution. Matched
# loosely on purpose: the site's own name may be tuned, but a page about this
# test will always contain this word.
try "landing page is this site" "yes" \
  body_contains "${BASE}/" "Wonderlic"

# HTML must revalidate. If it ever ships immutable, a deploy becomes invisible
# for up to a year to everyone who already visited, and no amount of
# redeploying fixes it — their browser will not ask again. This asserts the
# `fileOptions` block in sst.config.ts is still doing its job.
try "HTML is revalidated" "yes" \
  header_matches "${BASE}/" "cache-control" "must-revalidate"

if [ "$fails" -gt 0 ]; then
  echo "✗ ${fails} smoke check(s) failed"
  exit 1
fi
echo "✓ all smoke checks passed"
